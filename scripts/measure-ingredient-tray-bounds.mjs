import sharp from 'sharp'
import { writeFile } from 'node:fs/promises'

const fileIds = { noodle: 'noodle-sheet', egg: 'egg', 'hot-dog': 'hot-dog', sauce: 'sauce', scallion: 'scallion', cilantro: 'cilantro', onion: 'onion', 'chili-powder': 'chili-powder', 'turkey-noodle': 'turkey-noodle', cheese: 'cheese', corn: 'corn', orleans: 'orleans-chicken', bacon: 'bacon', tenderloin: 'tenderloin', enoki: 'enoki' }
const profiles = {}
for (const [id, file] of Object.entries(fileIds)) {
  const { data, info } = await sharp(`src/assets/runtime/menu/ingredients/ingredient-${file}.webp`).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  let left = info.width, top = info.height, right = 0, bottom = 0, mass = 0, xMass = 0, yMass = 0
  for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
    const alpha = data[(y * info.width + x) * 4 + 3]
    if (alpha <= 16) continue
    left = Math.min(left, x); right = Math.max(right, x)
    top = Math.min(top, y); bottom = Math.max(bottom, y)
    mass += alpha; xMass += (x + .5) * alpha; yMass += (y + .5) * alpha
  }
  profiles[id] = { sourceWidth: info.width, sourceHeight: info.height, bounds: { left, top, width: right + 1 - left, height: bottom + 1 - top }, center: { x: +((xMass / mass).toFixed(3)), y: +((yMass / mass).toFixed(3)) } }
}
await writeFile('src/landscape/kitchen/ingredientVisualBounds.ts', `// Generated by scripts/measure-ingredient-tray-bounds.mjs from runtime WebP alpha > 16.\n// Geometry only: the shared food image files are never cropped or changed.\nimport type { IngredientId } from '../campaign'\n\nexport const INGREDIENT_VISUAL_BOUNDS = ${JSON.stringify(profiles, null, 2)} satisfies Record<IngredientId, { sourceWidth: number; sourceHeight: number; bounds: { left: number; top: number; width: number; height: number }; center: { x: number; y: number } }>\n`)
